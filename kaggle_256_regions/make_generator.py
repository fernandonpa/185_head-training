"""Writes data_generation/sereega/simu_extended_source_regions.py: a copy of the team's SEREEGA generator (the original is not modified) in which, for a
fraction of the samples, the seed (centre) of the first patch is one of the target regions instead of a random region.

    python kaggle_256_regions/make_generator.py

Controlled by environment variables read by the copy:
    ESI_FORCE_REGIONS   comma-separated 0-based region indices (here: the 8 ground-truth regions of the coreg-spikes validation sessions)
    ESI_FORCE_FRACTION  share of the samples whose first patch is forced onto a target region (default 0.25)
The target regions are used in turn (sample k -> region k mod 8), so every region gets the same number of samples; the other patches of the sample, the
orders, amplitudes and times are drawn as before, and the generator's own overlap rule (margins) still applies.
"""
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "data_generation" / "sereega" / "simu_extended_source.py"
DST = REPO / "data_generation" / "sereega" / "simu_extended_source_regions.py"

s = SRC.read_text(encoding="utf8")

a1 = "match_dict ={}\n"
b1 = ('match_dict ={}\n'
      'FORCE_REGIONS = [int(x) for x in os.environ.get("ESI_FORCE_REGIONS", "").split(",") if x.strip()]\n'
      'FORCE_FRACTION = float(os.environ.get("ESI_FORCE_FRACTION", "0.25"))\n'
      'force_counter = 0\n')
a2 = "        seed                = int(np.random.choice(available_sources))\n"
b2 = ("        seed                = int(np.random.choice(available_sources))\n"
      "        if p == 1 and FORCE_REGIONS and np.random.rand() < FORCE_FRACTION:      # first patch: all regions are still available\n"
      "            seed = FORCE_REGIONS[force_counter % len(FORCE_REGIONS)]\n"
      "            force_counter += 1\n")
for a in (a1, a2):
    assert s.count(a) == 1, a
s = s.replace(a1, b1).replace(a2, b2)
DST.write_text("# GENERATED by kaggle_256_regions/make_generator.py from simu_extended_source.py - do not edit\n" + s, encoding="utf8")
print("written", DST)
